
# --------------------------------------------------
# .append()
# --------------------------------------------------
print("1. .append() Method")

candies = ["Chocolate", "Gummy Bears", "Lollipop", "Caramel"]

print("Original candy list:")
print(candies)

# Add a new candy to the end of the list
candies.append("Jelly Beans")

print("\nAfter append('Jelly Beans'):")
print(candies)

# --------------------------------------------------
# .insert()
# --------------------------------------------------
print("2. .insert() Method")



candies = ["Chocolate", "Gummy Bears", "Lollipop", "Caramel"]



print("Original candy list:")

print(candies)



# Insert a new candy at index 2

candies.insert(2, "Sour Patch Kids")



print("\nAfter insert(2, 'Sour Patch Kids'):")

print(candies)

